/**
 * Banco de perguntas do modo 1v1.
 *
 * Por que NAO reaproveitamos os exercicios da trilha: quase todos sao do tipo
 * `output_match`, que exige rodar Python de verdade para corrigir. Num duelo
 * cronometrado isso significaria carregar o Pyodide (uns 6 MB) antes de cada
 * partida e, pior, deixar a correcao no cliente - onde ela pode ser burlada.
 *
 * Aqui todas as perguntas sao de **multipla escolha** ou de **completar um
 * trecho curto de codigo**: os dois formatos se conferem com uma comparacao de
 * texto, o que permite manter a resposta certa dentro do banco de dados e
 * corrigir no servidor. O cliente nunca recebe o gabarito.
 *
 * A trilha so tem conteudo de Python; o duelo precisa das cinco linguagens
 * para o seletor de tema fazer sentido, entao este banco e proprio.
 */

