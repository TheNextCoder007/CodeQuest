/** Perguntas de um tema. `todas` devolve o banco inteiro. */
export const perguntasDoTema = (tema: string): PvpQuestion[] =>
  tema === 'todas'
    ? pvpQuestions
    : pvpQuestions.filter((questao) => questao.languageSlug === tema);
